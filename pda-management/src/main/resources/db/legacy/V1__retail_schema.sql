CREATE TABLE refresh_tokens (
 id VARCHAR2(36 CHAR) PRIMARY KEY, family_id VARCHAR2(36 CHAR) NOT NULL, user_id NUMBER(19) NOT NULL REFERENCES users(id), token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL, consumed_at TIMESTAMP(6) WITH TIME ZONE, revoked NUMBER(1) DEFAULT 0 NOT NULL CHECK (revoked IN (0, 1)), created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_refresh_user ON refresh_tokens(user_id);
CREATE INDEX ix_refresh_family ON refresh_tokens(family_id);
CREATE TABLE devices (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, device_code VARCHAR2(100 CHAR) NOT NULL UNIQUE, device_name VARCHAR2(255 CHAR) NOT NULL,
 store_id NUMBER(19) NOT NULL REFERENCES stores(id), registered_by NUMBER(19) NOT NULL, credential_hash CHAR(64) NOT NULL,
 fcm_token VARCHAR2(4000 BYTE), last_active_at TIMESTAMP(6) WITH TIME ZONE, created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 FOREIGN KEY(registered_by,store_id) REFERENCES users(id,store_id), UNIQUE(id,store_id)
);
CREATE UNIQUE INDEX ux_devices_fcm_token ON devices(fcm_token);
CREATE INDEX ix_devices_store_active ON devices(store_id,last_active_at);
CREATE TABLE pda_find_requests (
 id VARCHAR2(36 CHAR) PRIMARY KEY, requester_id NUMBER(19) NOT NULL, store_id NUMBER(19) NOT NULL, device_id NUMBER(19) NOT NULL,
 status VARCHAR2(20 CHAR) NOT NULL CHECK(status IN ('QUEUED','SENT','RINGING','STOPPED','EXPIRED','FAILED')),
 expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL, created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 FOREIGN KEY(requester_id,store_id) REFERENCES users(id,store_id), FOREIGN KEY(device_id,store_id) REFERENCES devices(id,store_id), UNIQUE(id,device_id)
);
CREATE INDEX ix_find_store_created ON pda_find_requests(store_id,created_at DESC);
CREATE INDEX ix_find_device ON pda_find_requests(device_id);
CREATE UNIQUE INDEX one_active_find ON pda_find_requests(
 CASE WHEN status IN ('QUEUED','SENT','RINGING') THEN device_id END
);
CREATE TABLE pda_alert_logs (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id VARCHAR2(36 CHAR) NOT NULL, device_id NUMBER(19) NOT NULL, event VARCHAR2(30 CHAR) NOT NULL,
 message VARCHAR2(500 CHAR), created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, FOREIGN KEY(request_id,device_id) REFERENCES pda_find_requests(id,device_id)
);
CREATE INDEX ix_alert_request ON pda_alert_logs(request_id);
CREATE TABLE products (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_code VARCHAR2(50 CHAR) NOT NULL UNIQUE, barcode VARCHAR2(50 CHAR) NOT NULL UNIQUE,
 product_name VARCHAR2(255 CHAR) NOT NULL, image_url VARCHAR2(1000 CHAR), image_version NUMBER(19) DEFAULT 0 NOT NULL,
 unit_price NUMBER(18,2) CHECK(unit_price >= 0), active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0, 1)),
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE product_image_sync_logs (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id NUMBER(19) NOT NULL REFERENCES products(id), image_url VARCHAR2(1000 CHAR), source_version NUMBER(19) NOT NULL,
 sync_status VARCHAR2(20 CHAR) NOT NULL CHECK(sync_status IN ('APPLIED','STALE')), created_by NUMBER(19) NOT NULL REFERENCES users(id), synced_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_image_product_synced ON product_image_sync_logs(product_id,synced_at DESC);
CREATE TABLE inventories (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id NUMBER(19) NOT NULL REFERENCES products(id), store_id NUMBER(19) NOT NULL REFERENCES stores(id),
 quantity NUMBER(18,2) DEFAULT 0 NOT NULL CHECK(quantity >= 0), version NUMBER(19) DEFAULT 0 NOT NULL CHECK(version >= 0),
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, UNIQUE(store_id,product_id)
);
CREATE INDEX ix_inventory_product ON inventories(product_id);
CREATE TABLE inventory_adjustments (
 id VARCHAR2(36 CHAR) PRIMARY KEY, product_id NUMBER(19) NOT NULL, store_id NUMBER(19) NOT NULL, old_qty NUMBER(18,2) NOT NULL CHECK(old_qty >= 0),
 new_qty NUMBER(18,2) NOT NULL CHECK(new_qty >= 0), expected_version NUMBER(19) NOT NULL, reason VARCHAR2(1000 CHAR) NOT NULL,
 created_by NUMBER(19) NOT NULL, created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 FOREIGN KEY(store_id,product_id) REFERENCES inventories(store_id,product_id), FOREIGN KEY(created_by,store_id) REFERENCES users(id,store_id)
);
CREATE INDEX ix_adjust_store_product_time ON inventory_adjustments(store_id,product_id,created_at DESC);
CREATE TABLE disposals (
 id VARCHAR2(36 CHAR) PRIMARY KEY, store_id NUMBER(19) NOT NULL REFERENCES stores(id), status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL CHECK(status IN ('PENDING','CONFIRMED','CANCELLED')),
 remarks VARCHAR2(1000 CHAR) NOT NULL, created_by NUMBER(19) NOT NULL, version NUMBER(19) DEFAULT 0 NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, FOREIGN KEY(created_by,store_id) REFERENCES users(id,store_id)
);
CREATE INDEX ix_disposals_store_created ON disposals(store_id,created_at DESC);
CREATE TABLE disposal_items (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, disposal_id VARCHAR2(36 CHAR) NOT NULL REFERENCES disposals(id), product_id NUMBER(19) NOT NULL REFERENCES products(id),
 quantity NUMBER(18,2) NOT NULL CHECK(quantity > 0), reason VARCHAR2(500 CHAR) NOT NULL, UNIQUE(disposal_id,product_id)
);
CREATE INDEX ix_disposal_items_product ON disposal_items(product_id);
CREATE TABLE disposal_histories (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, disposal_id VARCHAR2(36 CHAR) NOT NULL REFERENCES disposals(id), old_status VARCHAR2(20 CHAR), new_status VARCHAR2(20 CHAR) NOT NULL,
 changed_by NUMBER(19) NOT NULL REFERENCES users(id), changed_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_disposal_history_time ON disposal_histories(disposal_id,changed_at);
CREATE TABLE inventory_transactions (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id NUMBER(19) NOT NULL, store_id NUMBER(19) NOT NULL,
 transaction_type VARCHAR2(20 CHAR) NOT NULL CHECK(transaction_type IN ('ADJUSTMENT','DISPOSAL')),
 qty_before NUMBER(18,2) NOT NULL CHECK(qty_before >= 0), qty_change NUMBER(18,2) NOT NULL, qty_after NUMBER(18,2) NOT NULL CHECK(qty_after >= 0),
 adjustment_id VARCHAR2(36 CHAR) REFERENCES inventory_adjustments(id), disposal_id VARCHAR2(36 CHAR) REFERENCES disposals(id), created_by NUMBER(19) NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, CHECK(qty_before + qty_change = qty_after),
 CHECK((transaction_type='ADJUSTMENT' AND adjustment_id IS NOT NULL AND disposal_id IS NULL) OR (transaction_type='DISPOSAL' AND disposal_id IS NOT NULL AND adjustment_id IS NULL)),
 FOREIGN KEY(store_id,product_id) REFERENCES inventories(store_id,product_id), FOREIGN KEY(created_by,store_id) REFERENCES users(id,store_id),
 UNIQUE(adjustment_id)
);
CREATE INDEX ix_inv_tx_store_id ON inventory_transactions(store_id,id);
CREATE TABLE outbox_events (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_type VARCHAR2(30 CHAR) NOT NULL, aggregate_id VARCHAR2(100 CHAR) NOT NULL, payload CLOB NOT NULL CHECK (payload IS JSON),
 attempts NUMBER(10) DEFAULT 0 NOT NULL, available_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, processed_at TIMESTAMP(6) WITH TIME ZONE,
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX outbox_pending ON outbox_events(
 CASE WHEN processed_at IS NULL THEN available_at END,
 CASE WHEN processed_at IS NULL THEN id END
);
CREATE TABLE audit_logs (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id NUMBER(19) REFERENCES users(id), store_id NUMBER(19) REFERENCES stores(id),
 operation VARCHAR2(80 CHAR) NOT NULL, reference VARCHAR2(100 CHAR) NOT NULL, created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_audit_store_created ON audit_logs(store_id,created_at DESC);

-- Only disposal rows participate; adjustment rows have a NULL disposal_id.
CREATE UNIQUE INDEX ux_inv_tx_disposal_product ON inventory_transactions(
 CASE WHEN disposal_id IS NOT NULL THEN disposal_id END,
 CASE WHEN disposal_id IS NOT NULL THEN product_id END
);
