CREATE TABLE devices (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, device_code VARCHAR2(100 CHAR) NOT NULL UNIQUE, device_name VARCHAR2(255 CHAR) NOT NULL,
 store_id NUMBER(19) NOT NULL REFERENCES stores(id), registered_by NUMBER(19) NOT NULL, credential_hash CHAR(64) NOT NULL,
 fcm_token VARCHAR2(4000 BYTE), last_active_at TIMESTAMP(6) WITH TIME ZONE, created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 FOREIGN KEY(registered_by,store_id) REFERENCES users(id,store_id), UNIQUE(id,store_id)
);
CREATE UNIQUE INDEX ux_devices_fcm_token ON devices(fcm_token);
CREATE INDEX ix_devices_store_active ON devices(store_id,last_active_at);
