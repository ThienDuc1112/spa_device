CREATE TABLE disposals (
 id VARCHAR2(36 CHAR) PRIMARY KEY, store_id NUMBER(19) NOT NULL REFERENCES stores(id), status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL CHECK(status IN ('PENDING','CONFIRMED','CANCELLED')),
 remarks VARCHAR2(1000 CHAR) NOT NULL, created_by NUMBER(19) NOT NULL, version NUMBER(19) DEFAULT 0 NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, FOREIGN KEY(created_by,store_id) REFERENCES users(id,store_id)
);
CREATE INDEX ix_disposals_store_created ON disposals(store_id,created_at DESC);

CREATE TABLE disposal_items (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, disposal_id VARCHAR2(36 CHAR) NOT NULL REFERENCES disposals(id), product_id NUMBER(19) NOT NULL REFERENCES products(id),
 quantity NUMBER(18,2) NOT NULL CHECK(quantity > 0), reason VARCHAR2(500 CHAR) NOT NULL, UNIQUE(disposal_id,product_id)
);
CREATE INDEX ix_disposal_items_product ON disposal_items(product_id);

CREATE TABLE disposal_histories (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, disposal_id VARCHAR2(36 CHAR) NOT NULL REFERENCES disposals(id), old_status VARCHAR2(20 CHAR), new_status VARCHAR2(20 CHAR) NOT NULL,
 changed_by NUMBER(19) NOT NULL REFERENCES users(id), changed_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_disposal_history_time ON disposal_histories(disposal_id,changed_at);

