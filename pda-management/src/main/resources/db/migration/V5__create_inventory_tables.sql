-- Oracle Database 19c; use this migration history only with a new Oracle schema.
CREATE TABLE inventories (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id NUMBER(19) NOT NULL REFERENCES products(id), store_id NUMBER(19) NOT NULL REFERENCES stores(id),
 quantity NUMBER(18,2) DEFAULT 0 NOT NULL CHECK(quantity >= 0), version NUMBER(19) DEFAULT 0 NOT NULL CHECK(version >= 0),
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, UNIQUE(store_id,product_id)
);
CREATE INDEX ix_inventory_product ON inventories(product_id);

CREATE TABLE inventory_adjustments (
 id VARCHAR2(36 CHAR) PRIMARY KEY, product_id NUMBER(19) NOT NULL, store_id NUMBER(19) NOT NULL, old_qty NUMBER(18,2) NOT NULL CHECK(old_qty >= 0),
 new_qty NUMBER(18,2) NOT NULL CHECK(new_qty >= 0), expected_version NUMBER(19) NOT NULL, reason VARCHAR2(1000 CHAR) NOT NULL,
 created_by NUMBER(19) NOT NULL, created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 FOREIGN KEY(store_id,product_id) REFERENCES inventories(store_id,product_id), FOREIGN KEY(created_by,store_id) REFERENCES users(id,store_id)
);
CREATE INDEX ix_adjust_store_product_time ON inventory_adjustments(store_id,product_id,created_at DESC);

CREATE TABLE inventory_transactions (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id NUMBER(19) NOT NULL, store_id NUMBER(19) NOT NULL,
 transaction_type VARCHAR2(20 CHAR) NOT NULL CHECK(transaction_type IN ('ADJUSTMENT','DISPOSAL')),
 qty_before NUMBER(18,2) NOT NULL CHECK(qty_before >= 0), qty_change NUMBER(18,2) NOT NULL, qty_after NUMBER(18,2) NOT NULL CHECK(qty_after >= 0),
 adjustment_id VARCHAR2(36 CHAR) REFERENCES inventory_adjustments(id), disposal_id VARCHAR2(36 CHAR), created_by NUMBER(19) NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, CHECK(qty_before + qty_change = qty_after),
 CHECK((transaction_type='ADJUSTMENT' AND adjustment_id IS NOT NULL AND disposal_id IS NULL) OR (transaction_type='DISPOSAL' AND disposal_id IS NOT NULL AND adjustment_id IS NULL)),
 FOREIGN KEY(store_id,product_id) REFERENCES inventories(store_id,product_id), FOREIGN KEY(created_by,store_id) REFERENCES users(id,store_id),
 UNIQUE(adjustment_id)
);
CREATE INDEX ix_inv_tx_store_id ON inventory_transactions(store_id,id);

-- Only disposal rows participate; adjustment rows have a NULL disposal_id.
CREATE UNIQUE INDEX ux_inv_tx_disposal_product ON inventory_transactions(
 CASE WHEN disposal_id IS NOT NULL THEN disposal_id END,
 CASE WHEN disposal_id IS NOT NULL THEN product_id END
);
