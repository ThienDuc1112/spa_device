CREATE TABLE stores (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, store_code VARCHAR2(50 CHAR) NOT NULL UNIQUE, store_name VARCHAR2(255 CHAR) NOT NULL,
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE users (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR2(100 CHAR) NOT NULL UNIQUE, password_hash VARCHAR2(255 CHAR) NOT NULL,
 full_name VARCHAR2(255 CHAR), email VARCHAR2(255 CHAR), store_id NUMBER(19) NOT NULL REFERENCES stores(id),
 active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0, 1)), created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 UNIQUE(id, store_id)
);
CREATE INDEX ix_users_store ON users(store_id);

CREATE TABLE roles (id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role_name VARCHAR2(50 CHAR) NOT NULL UNIQUE, description VARCHAR2(255 CHAR));

CREATE TABLE user_roles (user_id NUMBER(19) NOT NULL REFERENCES users(id), role_id NUMBER(19) NOT NULL REFERENCES roles(id), PRIMARY KEY(user_id,role_id));
CREATE INDEX ix_user_roles_role ON user_roles(role_id);
