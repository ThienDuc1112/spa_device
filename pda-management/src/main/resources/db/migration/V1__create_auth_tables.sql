CREATE TABLE refresh_tokens (
 id VARCHAR2(36 CHAR) PRIMARY KEY, family_id VARCHAR2(36 CHAR) NOT NULL, user_id NUMBER(19) NOT NULL REFERENCES users(id), token_hash CHAR(64) NOT NULL UNIQUE,
 expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL, consumed_at TIMESTAMP(6) WITH TIME ZONE, revoked NUMBER(1) DEFAULT 0 NOT NULL CHECK (revoked IN (0, 1)), created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_refresh_user ON refresh_tokens(user_id);
CREATE INDEX ix_refresh_family ON refresh_tokens(family_id);

CREATE TABLE audit_logs (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id NUMBER(19) REFERENCES users(id), store_id NUMBER(19) REFERENCES stores(id),
 operation VARCHAR2(80 CHAR) NOT NULL, reference VARCHAR2(100 CHAR) NOT NULL, created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_audit_store_created ON audit_logs(store_id,created_at DESC);
