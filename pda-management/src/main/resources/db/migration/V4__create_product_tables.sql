CREATE TABLE products (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_code VARCHAR2(50 CHAR) NOT NULL UNIQUE, barcode VARCHAR2(50 CHAR) NOT NULL UNIQUE,
 product_name VARCHAR2(255 CHAR) NOT NULL, image_url VARCHAR2(1000 CHAR), image_version NUMBER(19) DEFAULT 0 NOT NULL,
 unit_price NUMBER(18,2) CHECK(unit_price >= 0), active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0, 1)),
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE product_image_sync_logs (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id NUMBER(19) NOT NULL REFERENCES products(id), image_url VARCHAR2(1000 CHAR), source_version NUMBER(19) NOT NULL,
 sync_status VARCHAR2(20 CHAR) NOT NULL CHECK(sync_status IN ('APPLIED','STALE')), created_by NUMBER(19) NOT NULL REFERENCES users(id), synced_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_image_product_synced ON product_image_sync_logs(product_id,synced_at DESC);
