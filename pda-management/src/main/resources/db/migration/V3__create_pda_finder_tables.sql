CREATE TABLE pda_find_requests (
 id VARCHAR2(36 CHAR) PRIMARY KEY, requester_id NUMBER(19) NOT NULL, store_id NUMBER(19) NOT NULL, device_id NUMBER(19) NOT NULL,
 status VARCHAR2(20 CHAR) NOT NULL CHECK(status IN ('QUEUED','SENT','RINGING','STOPPED','EXPIRED','FAILED')),
 expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL, created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, updated_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 FOREIGN KEY(requester_id,store_id) REFERENCES users(id,store_id), FOREIGN KEY(device_id,store_id) REFERENCES devices(id,store_id), UNIQUE(id,device_id)
);
CREATE INDEX ix_find_store_created ON pda_find_requests(store_id,created_at DESC);
CREATE INDEX ix_find_device ON pda_find_requests(device_id);
CREATE UNIQUE INDEX one_active_find ON pda_find_requests(
 CASE WHEN status IN ('QUEUED','SENT','RINGING') THEN device_id END
);

CREATE TABLE pda_alert_logs (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id VARCHAR2(36 CHAR) NOT NULL, device_id NUMBER(19) NOT NULL, event VARCHAR2(30 CHAR) NOT NULL,
 message VARCHAR2(500 CHAR), created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, FOREIGN KEY(request_id,device_id) REFERENCES pda_find_requests(id,device_id)
);
CREATE INDEX ix_alert_request ON pda_alert_logs(request_id);

CREATE TABLE outbox_events (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_type VARCHAR2(30 CHAR) NOT NULL, aggregate_id VARCHAR2(100 CHAR) NOT NULL, payload CLOB NOT NULL CHECK (payload IS JSON),
 attempts NUMBER(10) DEFAULT 0 NOT NULL, available_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, processed_at TIMESTAMP(6) WITH TIME ZONE,
 created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX outbox_pending ON outbox_events(
 CASE WHEN processed_at IS NULL THEN available_at END,
 CASE WHEN processed_at IS NULL THEN id END
);
